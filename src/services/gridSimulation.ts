// Helper to generate 24-hour diurnal profile deterministically
export function generate24HourProfile(
  meterId: string,
  sanctionedKw: number,
  tamperState: TamperState,
  currentPowerKw?: number,
  currentWaterLph?: number
): HourlyReadingPoint[] {
  const points: HourlyReadingPoint[] = [];

  for (let h = 0; h < 24; h++) {
    const n1 = seededNoise(`${meterId}-p-${h}`);
    const n2 = seededNoise(`${meterId}-w-${h}`);

    let diurnalPowerFactor = 0.32;
    let diurnalWaterFactor = 0.08;

    if (h >= 6 && h <= 9) {
      diurnalPowerFactor = 0.85 + Math.sin(((h - 6) / 3) * Math.PI) * 0.35;
      diurnalWaterFactor = 0.80 + Math.sin(((h - 6) / 3) * Math.PI) * 0.40;
    } else if (h >= 10 && h <= 16) {
      diurnalPowerFactor = 0.48;
      diurnalWaterFactor = 0.25;
    } else if (h >= 17 && h <= 22) {
      diurnalPowerFactor = 0.95 + Math.sin(((h - 17) / 5) * Math.PI) * 0.40;
      diurnalWaterFactor = 0.78 + Math.sin(((h - 17) / 5) * Math.PI) * 0.35;
    }

    let power = Number((sanctionedKw * 0.55 * diurnalPowerFactor + (n1 * 0.26 - 0.13)).toFixed(2));
    let water = Number((32 * diurnalWaterFactor + (n2 * 3.6 - 1.8)).toFixed(1));

    if (power < 0.15) power = 0.20;
    if (water < 0) water = 0;

    // Apply scenario tamper adjustments
    if (tamperState === 'meter_bypass') {
      if (h >= 12) {
        power = Number((0.03 + n1 * 0.03).toFixed(2));
        water = Math.max(water, Number((28.0 + n2 * 12.0).toFixed(1)));
      }
    } else if (tamperState === 'crypto_mining') {
      if (h >= 10) {
        power = Number((sanctionedKw * 2.25 + n1 * 0.45).toFixed(2));
      }
    } else if (tamperState === 'vacation') {
      power = Number((0.10 + n1 * 0.04).toFixed(2));
      water = Number((n2 * 0.2).toFixed(1));
    }

    if (h === 18 && currentPowerKw !== undefined && currentWaterLph !== undefined) {
      power = currentPowerKw;
      water = currentWaterLph;
    }

    const classificationResult = classifyMultiSourceReading({
      powerKw: power,
      waterLph: water,
      sanctionedLoadKw: sanctionedKw,
      consecutiveOveruseHours: h >= 10 && tamperState === 'crypto_mining' ? h - 10 : 0,
      hourOfDay: h,
    });

    points.push({
      hour: h,
      timeLabel: `${h.toString().padStart(2, '0')}:00`,
      powerKw: power,
      waterLph: water,
      occupancyScore: classificationResult.occupancyConsistencyIndex,
      classification: classificationResult.classification,
    });
  }

  return points;
}

